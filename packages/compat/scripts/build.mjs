import { build } from "esbuild";
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const output = new URL(
  "../../../apps/ios/Folio/Resources/Compat/",
  import.meta.url,
);
const check = process.argv.includes("--check");
for (const name of [
  "bridge",
  "diagnostics",
  "input-log",
  "focus-environment",
  "focus-reveal-guard",
  "touch-shortcuts",
  "resize-edges",
  "touch-gestures",
  "pencil",
  "canvas-wheel",
  "ua-button-color",
  "hide-google",
  "phone-layout",
  "input-lab",
  "memory-lab",
  "dom-probe",
  "file-availability",
]) {
  const result = await build({
    entryPoints: [fileURLToPath(new URL(`../src/${name}.ts`, import.meta.url))],
    bundle: true,
    format: "iife",
    target: "safari26",
    write: false,
    banner: {
      js: "// Folio compat 0.1.0. Generated by pnpm build; edit packages/compat/src.",
    },
  });
  const text = result.outputFiles[0].text;
  const path = new URL(`${name}.js`, output);
  if (check) {
    let existing;
    try {
      existing = await readFile(path, "utf8");
    } catch {
      existing = undefined;
    }
    if (existing !== text)
      throw new Error(`Stale bundle: ${fileURLToPath(path)}. Run pnpm build.`);
  } else {
    await mkdir(output, { recursive: true });
    await writeFile(path, text);
  }
}
console.log(check ? "Compat bundles match sources." : "Compat bundles built.");

for (const name of ["input-lab", "memory-lab", "focus-lab"]) {
  const html = await readFile(
    new URL(`../src/${name}.html`, import.meta.url),
    "utf8",
  );
  const path = new URL(`${name}.html`, output);
  if (check) {
    if ((await readFile(path, "utf8")) !== html)
      throw new Error(`Stale ${name} HTML. Run pnpm build.`);
  } else await writeFile(path, html);
}
